"""Native PostgreSQL Kanban schema; frozen source schema maintained explicitly."""
SCHEMA_SQL = r'''
CREATE TABLE IF NOT EXISTS kanban_notify_subs (
    task_id       TEXT NOT NULL,
    platform      TEXT NOT NULL,
    chat_id       TEXT NOT NULL,
    thread_id     TEXT NOT NULL DEFAULT '',
    user_id       TEXT,
    user_id_alt   TEXT,
    chat_type     TEXT,
    notifier_profile TEXT,
    delivery_mode TEXT NOT NULL DEFAULT 'notify',
    delivery_metadata TEXT,
    created_at    BIGINT NOT NULL,
    last_event_id BIGINT NOT NULL DEFAULT 0,
    last_ping_event_id BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (task_id, platform, chat_id, thread_id)
);
CREATE TABLE IF NOT EXISTS task_attachments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      TEXT NOT NULL,
    filename     TEXT NOT NULL,
    stored_path  TEXT NOT NULL,
    content_type TEXT,
    size         BIGINT NOT NULL DEFAULT 0,
    uploaded_by  TEXT,
    created_at   BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS task_comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    TEXT NOT NULL,
    author     TEXT NOT NULL,
    body       TEXT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS task_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    TEXT NOT NULL,
    run_id     BIGINT,
    kind       TEXT NOT NULL,
    payload    TEXT,
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS task_links (
    parent_id  TEXT NOT NULL,
    child_id   TEXT NOT NULL,
    PRIMARY KEY (parent_id, child_id)
);
CREATE TABLE IF NOT EXISTS task_runs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id             TEXT NOT NULL,
    profile             TEXT,
    step_key            TEXT,
    status              TEXT NOT NULL,

    claim_lock          TEXT,
    claim_expires       BIGINT,
    worker_pid          BIGINT,



    worker_started_at   TEXT,
    max_runtime_seconds BIGINT,
    last_heartbeat_at   BIGINT,
    started_at          BIGINT NOT NULL,
    ended_at            BIGINT,
    outcome             TEXT,


    summary             TEXT,
    metadata            TEXT,
    error               TEXT
);
CREATE TABLE IF NOT EXISTS tasks (
    id                   TEXT PRIMARY KEY,
    title                TEXT NOT NULL,
    body                 TEXT,
    assignee             TEXT,
    status               TEXT NOT NULL,
    priority             BIGINT DEFAULT 0,
    created_by           TEXT,
    created_at           BIGINT NOT NULL,
    started_at           BIGINT,
    completed_at         BIGINT,
    workspace_kind       TEXT NOT NULL DEFAULT 'scratch',
    workspace_path       TEXT,
    branch_name          TEXT,



    project_id           TEXT,
    claim_lock           TEXT,
    claim_expires        BIGINT,
    tenant               TEXT,
    result               TEXT,
    idempotency_key      TEXT,




    consecutive_failures BIGINT NOT NULL DEFAULT 0,
    worker_pid           BIGINT,






    worker_started_at    TEXT,

    last_failure_error   TEXT,
    max_runtime_seconds  BIGINT,
    last_heartbeat_at    BIGINT,


    current_run_id       BIGINT,



    workflow_template_id TEXT,
    current_step_key     TEXT,


    skills               TEXT,



    model_override       TEXT,




    provider_override    TEXT,




    reasoning_effort     TEXT,





    max_retries          BIGINT,






    goal_mode            BIGINT NOT NULL DEFAULT 0,


    goal_max_turns       BIGINT,






    session_id           TEXT,





    block_kind           TEXT,






    block_recurrences    BIGINT NOT NULL DEFAULT 0
, completion_contract TEXT);
'''
