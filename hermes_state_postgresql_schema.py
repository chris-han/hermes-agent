"""Native PostgreSQL schema v1; packaged with the persistence owner."""
SCHEMA_SQL = r'''
-- Native PostgreSQL schema v1. Scope is the containing namespace; native IDs remain unchanged.
CREATE TABLE IF NOT EXISTS schema_version (
    version BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS system_prompts (
    hash TEXT PRIMARY KEY,
    prompt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
    id TEXT PRIMARY KEY,
    runtime_revision BIGINT NOT NULL DEFAULT 0,
    runtime_generation BIGINT NOT NULL DEFAULT 0,
    source TEXT NOT NULL,
    created_source TEXT,
    user_id TEXT,
    session_key TEXT,
    chat_id TEXT,
    chat_type TEXT,
    thread_id TEXT,
    display_name TEXT,
    origin_json TEXT,
    expiry_finalized BIGINT DEFAULT 0,
    model TEXT,
    model_config TEXT,
    system_prompt TEXT,
    system_prompt_hash TEXT,
    parent_session_id TEXT,
    started_at DOUBLE PRECISION NOT NULL,
    ended_at DOUBLE PRECISION,
    end_reason TEXT,
    message_count BIGINT DEFAULT 0,
    tool_call_count BIGINT DEFAULT 0,
    input_tokens BIGINT DEFAULT 0,
    output_tokens BIGINT DEFAULT 0,
    cache_read_tokens BIGINT DEFAULT 0,
    cache_write_tokens BIGINT DEFAULT 0,
    reasoning_tokens BIGINT DEFAULT 0,
    cwd TEXT,
    git_branch TEXT,
    git_repo_root TEXT,
    git_metadata_generation BIGINT NOT NULL DEFAULT 0,
    billing_provider TEXT,
    billing_base_url TEXT,
    billing_mode TEXT,
    estimated_cost_usd DOUBLE PRECISION,
    actual_cost_usd DOUBLE PRECISION,
    cost_status TEXT,
    cost_source TEXT,
    pricing_version TEXT,
    title TEXT,
    title_source TEXT,
    last_activity_at DOUBLE PRECISION,
    last_activity_description TEXT,
    last_activity_provenance TEXT,
    api_call_count BIGINT DEFAULT 0,
    handoff_state TEXT,
    handoff_platform TEXT,
    handoff_error TEXT,
    compression_failure_cooldown_until DOUBLE PRECISION,
    compression_failure_error TEXT,
    compression_fallback_streak BIGINT NOT NULL DEFAULT 0,
    compression_ineffective_count BIGINT NOT NULL DEFAULT 0,
    compression_recovery_deadline DOUBLE PRECISION,
    compression_overload_streak BIGINT NOT NULL DEFAULT 0,
    profile_name TEXT,
    transport_profile TEXT,
    rewind_count BIGINT NOT NULL DEFAULT 0,
    archived BIGINT NOT NULL DEFAULT 0,
    auto_archived BIGINT NOT NULL DEFAULT 0,
    pinned BIGINT NOT NULL DEFAULT 0,
    hidden BIGINT NOT NULL DEFAULT 0,
    last_read_at DOUBLE PRECISION,
    tool_names TEXT,
    FOREIGN KEY (parent_session_id) REFERENCES sessions(id) DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (system_prompt_hash) REFERENCES system_prompts(hash) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES sessions(id) DEFERRABLE INITIALLY DEFERRED,
    role TEXT NOT NULL,
    content TEXT,
    tool_call_id TEXT,
    tool_calls TEXT,
    tool_name TEXT,
    effect_disposition TEXT,
    timestamp DOUBLE PRECISION NOT NULL,
    token_count BIGINT,
    finish_reason TEXT,
    reasoning TEXT,
    reasoning_content TEXT,
    reasoning_details TEXT,
    codex_reasoning_items TEXT,
    codex_message_items TEXT,
    platform_message_id TEXT,
    observed BIGINT DEFAULT 0,
    _compressed_summary BIGINT NOT NULL DEFAULT 0,
    active BIGINT NOT NULL DEFAULT 1,
    compacted BIGINT NOT NULL DEFAULT 0,
    api_content TEXT,
    display_kind TEXT,
    display_metadata TEXT,
    display_identity BYTEA,
    display_order BIGINT,
    message_uid TEXT,
    absorbed_message_uids TEXT,
    tool_call_uids TEXT,
    tool_call_uid TEXT
);

CREATE TABLE IF NOT EXISTS session_model_usage (
    session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    model TEXT NOT NULL,
    billing_provider TEXT NOT NULL DEFAULT '',
    billing_base_url TEXT NOT NULL DEFAULT '',
    billing_mode TEXT NOT NULL DEFAULT '',
    task TEXT NOT NULL DEFAULT '',
    api_call_count BIGINT NOT NULL DEFAULT 0,
    input_tokens BIGINT NOT NULL DEFAULT 0,
    output_tokens BIGINT NOT NULL DEFAULT 0,
    cache_read_tokens BIGINT NOT NULL DEFAULT 0,
    cache_write_tokens BIGINT NOT NULL DEFAULT 0,
    reasoning_tokens BIGINT NOT NULL DEFAULT 0,
    estimated_cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
    actual_cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
    cost_status TEXT,
    cost_source TEXT,
    first_seen DOUBLE PRECISION,
    last_seen DOUBLE PRECISION,
    PRIMARY KEY (session_id, model, billing_provider, billing_base_url, billing_mode, task)
);

CREATE TABLE IF NOT EXISTS runtime_epoch (
    singleton BIGINT PRIMARY KEY CHECK (singleton = 1),
    epoch BIGINT NOT NULL CHECK (epoch > 0),
    instance_id TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS session_admissions (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_id TEXT NOT NULL UNIQUE,
    request_id TEXT NOT NULL,
    principal_id TEXT NOT NULL,
    target_session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE RESTRICT,
    lineage_json TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    payload_digest TEXT NOT NULL,
    intent TEXT NOT NULL CHECK (intent IN ('queue','steer','redirect')),
    status TEXT NOT NULL CHECK (status IN ('queued','started','unknown','terminal')),
    outcome TEXT,
    owner_epoch BIGINT,
    generation BIGINT,
    UNIQUE (principal_id, target_session_id, request_id),
    CHECK (status != 'started' OR (owner_epoch IS NOT NULL AND generation IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS worker_executions (
    execution_id TEXT PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE RESTRICT,
    kind TEXT NOT NULL CHECK (kind IN ('cron','child','compute','kanban')),
    owner_epoch BIGINT NOT NULL,
    generation BIGINT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('registered','running','unknown','terminal')),
    adoption_digest TEXT NOT NULL,
    last_sequence BIGINT NOT NULL DEFAULT 0 CHECK (last_sequence >= 0)
);

CREATE TABLE IF NOT EXISTS worker_receipts (
    execution_id TEXT NOT NULL REFERENCES worker_executions(execution_id) ON DELETE RESTRICT,
    sequence BIGINT NOT NULL CHECK (sequence > 0),
    payload_digest TEXT NOT NULL,
    result_json TEXT NOT NULL,
    PRIMARY KEY (execution_id, sequence)
);

CREATE TABLE IF NOT EXISTS state_meta (
    key TEXT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS gateway_routing (
    scope TEXT NOT NULL DEFAULT '',
    session_key TEXT NOT NULL,
    entry_json TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (scope, session_key)
);

CREATE TABLE IF NOT EXISTS gateway_hygiene_state (
    session_key TEXT PRIMARY KEY,
    failure_streak BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS conversation_generations (
    source TEXT NOT NULL,
    session_key TEXT NOT NULL,
    generation BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (source, session_key)
);

CREATE TABLE IF NOT EXISTS gateway_heartbeats (
    backend_id TEXT PRIMARY KEY,
    pid BIGINT NOT NULL,
    started_at DOUBLE PRECISION NOT NULL,
    last_heartbeat DOUBLE PRECISION NOT NULL,
    profile TEXT NOT NULL DEFAULT '',
    host TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS compression_locks (
    session_id TEXT PRIMARY KEY,
    holder TEXT NOT NULL,
    acquired_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS session_turn_leases (
    conversation_id TEXT PRIMARY KEY,
    holder TEXT NOT NULL,
    acquired_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS async_delegations (
    delegation_id TEXT PRIMARY KEY,
    origin_session TEXT NOT NULL,
    origin_ui_session_id TEXT NOT NULL DEFAULT '',
    parent_session_id TEXT,
    state TEXT NOT NULL,
    dispatched_at DOUBLE PRECISION NOT NULL,
    completed_at DOUBLE PRECISION,
    updated_at DOUBLE PRECISION NOT NULL,
    event_json TEXT,
    result_json TEXT,
    delivery_state TEXT NOT NULL DEFAULT 'pending',
    delivery_attempts BIGINT NOT NULL DEFAULT 0,
    delivered_at DOUBLE PRECISION,
    owner_pid BIGINT,
    owner_started_at BIGINT,
    task_json TEXT,
    
    owner_execution_id TEXT,
    delivery_claim TEXT,
    delivery_claimed_at DOUBLE PRECISION,
    
    
    
    
    
    
    
    
    origin_session_id TEXT NOT NULL DEFAULT ''
);

ALTER TABLE messages ADD COLUMN IF NOT EXISTS content_bytes BYTEA;

CREATE TABLE IF NOT EXISTS run_idempotency (
 scope TEXT NOT NULL, idempotency_key TEXT NOT NULL, fingerprint TEXT NOT NULL,
 run_id TEXT NOT NULL UNIQUE, status_json TEXT NOT NULL, owner_pid BIGINT NOT NULL DEFAULT 0,
 owner_started BIGINT NOT NULL DEFAULT 0, retention_until DOUBLE PRECISION NOT NULL DEFAULT 0,
 acknowledged_at DOUBLE PRECISION, created_at DOUBLE PRECISION NOT NULL, updated_at DOUBLE PRECISION NOT NULL,
 PRIMARY KEY(scope,idempotency_key));
CREATE TABLE IF NOT EXISTS responses(response_id TEXT PRIMARY KEY,data TEXT NOT NULL,accessed_at DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS conversations(name TEXT PRIMARY KEY,response_id TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS response_keys(request_key TEXT PRIMARY KEY,fingerprint TEXT NOT NULL,created_at BIGINT NOT NULL,
 model_json TEXT,settled_at DOUBLE PRECISION,response_id TEXT);
CREATE TABLE IF NOT EXISTS response_admissions(request_key TEXT PRIMARY KEY,admission_id TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS response_output_order(request_key TEXT NOT NULL,item_id TEXT NOT NULL,output_index BIGINT NOT NULL,
 PRIMARY KEY(request_key,item_id),UNIQUE(request_key,output_index));

CREATE TABLE IF NOT EXISTS executions(
 id TEXT PRIMARY KEY,job_id TEXT NOT NULL,source TEXT NOT NULL,process_id TEXT NOT NULL,pid BIGINT NOT NULL,
 process_started_at BIGINT,status TEXT NOT NULL CHECK(status IN('claimed','running','completed','failed','unknown')),
 handoff_pending BIGINT NOT NULL DEFAULT 0,handoff_started_at DOUBLE PRECISION,claimed_at TEXT NOT NULL,
 started_at TEXT,finished_at TEXT,error TEXT,delivery_outcome TEXT,scheduled_instant TEXT,progress_at TEXT,
 owner_host TEXT);
CREATE INDEX IF NOT EXISTS executions_job_pg ON executions(job_id,claimed_at DESC,id DESC);
CREATE TABLE IF NOT EXISTS cron_incidents(
 id TEXT PRIMARY KEY,job_id TEXT NOT NULL,error_sig TEXT NOT NULL,state TEXT NOT NULL,
 failure_type TEXT NOT NULL DEFAULT 'unknown',first_seen_at TEXT NOT NULL,last_seen_at TEXT NOT NULL,
 acked_at TEXT,alerted_at TEXT,closed_at TEXT,error TEXT NOT NULL,output_file TEXT);
CREATE TABLE IF NOT EXISTS hosted_room_legacy_imports(source TEXT PRIMARY KEY,imported_at DOUBLE PRECISION NOT NULL,rooms BIGINT NOT NULL DEFAULT 0);
'''
