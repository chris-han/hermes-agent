                    decision_id TEXT NOT NULL,
                    decision_hash TEXT NOT NULL,
                    authoritative_candidate_id TEXT NOT NULL,
                    authoritative_candidate_hash TEXT NOT NULL,
                    source_ref TEXT NOT NULL,
