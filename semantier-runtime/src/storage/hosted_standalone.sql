-- Explicit native PostgreSQL schemas for standalone deterministic owners.
CREATE TABLE IF NOT EXISTS events (
            event_id TEXT PRIMARY KEY,
            event_type TEXT NOT NULL,
            org_id TEXT,
            stream_id TEXT,
            correlation_id TEXT,
            occurred_at TEXT NOT NULL,
            payload_json TEXT NOT NULL,
            
            -- EOS extensions
            ontology_version TEXT,
            projection_version INTEGER,
            content_hash TEXT,
            prior_event_hash TEXT,
            signature TEXT,
            
            created_at TEXT NOT NULL
        );

CREATE TABLE IF NOT EXISTS projection_versions (
            projection_id TEXT PRIMARY KEY,
            org_id TEXT NOT NULL,
            ontology_version TEXT NOT NULL,
            version INTEGER NOT NULL,
            semantic_projection_input_json TEXT,
            semantic_scope_json TEXT,
            bindings_json TEXT,
            constraint_layer_json TEXT,
            created_at TEXT NOT NULL,
            UNIQUE(org_id, ontology_version, version)
        );

CREATE TABLE IF NOT EXISTS idempotency_keys (
            key TEXT PRIMARY KEY,
            org_id TEXT,
            intent_hash TEXT,
            registered_at TEXT NOT NULL
        );

CREATE TABLE IF NOT EXISTS approvals (
            id TEXT PRIMARY KEY,
            idempotency_key TEXT NOT NULL,
            approver TEXT NOT NULL,
            approved_at TEXT NOT NULL,
            metadata_json TEXT,
            UNIQUE(idempotency_key, approver)
        );

CREATE TABLE IF NOT EXISTS semantic_drafts (
            conversation_id TEXT PRIMARY KEY,
            org_id TEXT NOT NULL,
            tags_json TEXT,
            amount TEXT,
            currency TEXT,
            counterparty TEXT,
            invoice_ref TEXT,
            evidence_refs_json TEXT,
            missing_fields_json TEXT,
            status TEXT NOT NULL,
            payload_json TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        );

CREATE TABLE IF NOT EXISTS domain_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                event_type TEXT,
                payload_json TEXT,
                created_at timestamptz DEFAULT CURRENT_TIMESTAMP
            );

CREATE TABLE IF NOT EXISTS execution_events (
                event_id TEXT PRIMARY KEY,
                event_type TEXT NOT NULL,
                occurred_at TEXT NOT NULL,
                correlation_id TEXT NOT NULL,
                payload_json TEXT NOT NULL
            );

CREATE TABLE IF NOT EXISTS standalone_imports(source_store_id text PRIMARY KEY,source_path text NOT NULL,source_fingerprint text NOT NULL,receipt_json jsonb NOT NULL,imported_at timestamptz NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS runtime_detection_snapshots (
                    run_id TEXT PRIMARY KEY,
                    workspace_id TEXT NOT NULL,
                    schema_version TEXT NOT NULL,
                    experiment_id TEXT NOT NULL,
                    input_source_ref TEXT NOT NULL,
                    input_source_hash TEXT NOT NULL,
                    profile_ref TEXT NOT NULL,
                    profile_version TEXT NOT NULL,
                    graph_version_ref TEXT NOT NULL,
                    graph_checksum TEXT NOT NULL,
                    ontology_version_ref TEXT,
                    ontology_checksum TEXT,
                    skill_ref TEXT NOT NULL,
                    semantica_commit TEXT NOT NULL,
                    matcher_version TEXT NOT NULL,
                    findings_hash TEXT NOT NULL,
                    finding_refs_json TEXT NOT NULL,
                    findings_json TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );

CREATE TABLE IF NOT EXISTS semantic_feedback_events (
                    feedback_id TEXT PRIMARY KEY,
                    workspace_id TEXT NOT NULL,
                    schema_version TEXT NOT NULL,
                    run_id TEXT NOT NULL,
                    finding_id TEXT NOT NULL,
                    action TEXT NOT NULL CHECK (action IN ('confirm', 'change', 'dismiss')),
                    original_result_ref TEXT NOT NULL,
                    corrected_result_json TEXT,
                    reason_code TEXT,
                    justification TEXT,
                    evidence_ref TEXT NOT NULL,
                    graph_version_ref TEXT NOT NULL,
                    ontology_version_ref TEXT,
                    profile_ref TEXT NOT NULL,
                    profile_version TEXT NOT NULL,
                    skill_ref TEXT NOT NULL,
                    derivation_refs_json TEXT NOT NULL,
                    reviewer TEXT NOT NULL,
                    occurred_at TEXT NOT NULL,
                    event_hash TEXT NOT NULL
                , event_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);

CREATE TABLE IF NOT EXISTS canonical_list_profile_versions (
                    profile_ref TEXT NOT NULL,
                    version TEXT NOT NULL,
                    workspace_id TEXT NOT NULL,
                    schema_version TEXT NOT NULL,
                    content_hash TEXT NOT NULL,
                    role_mapping_json TEXT NOT NULL,
                    runtime_policy_json TEXT NOT NULL,
                    created_by TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    supersedes_version TEXT,
                    PRIMARY KEY (workspace_id, profile_ref, version)
                );

CREATE TABLE IF NOT EXISTS mvl_selections (
                    selection_id TEXT PRIMARY KEY,
                    schema_version TEXT NOT NULL,
                    experiment_id TEXT NOT NULL,
                    workspace_id TEXT NOT NULL,
                    profile_ref TEXT NOT NULL,
                    profile_version TEXT NOT NULL,
                    graph_version_ref TEXT NOT NULL,
                    ontology_version_ref TEXT,
                    graph_semantica_version_id TEXT NOT NULL,
                    ontology_semantica_version_id TEXT,
                    graph_tag TEXT NOT NULL,
                    ontology_tag TEXT,
                    graph_checksum TEXT NOT NULL,
                    ontology_checksum TEXT,
                    selected_by TEXT NOT NULL,
                    selected_at TEXT NOT NULL,
                    supersedes_selection_id TEXT,
                    status TEXT NOT NULL CHECK (status IN ('active', 'superseded')),
                    UNIQUE (workspace_id, graph_version_ref),
                    UNIQUE (workspace_id, ontology_version_ref)
                );

CREATE TABLE IF NOT EXISTS effective_skill_versions (
                    effective_id TEXT PRIMARY KEY,
                    workspace_id TEXT NOT NULL,
